package tulpor

import (
	"os"
	"testing"
)

// The Android app generates configs in this shape (see app ConfigBuilder.kt).
func TestVpnConfigLoads(t *testing.T) {
	b, err := os.ReadFile("testdata/vpn_config.json")
	if err != nil {
		t.Fatal(err)
	}
	inst, err := newInstance(string(b))
	if err != nil {
		t.Fatalf("config rejected by xray: %v", err)
	}
	inst.Close()
}

func TestMeasureDelayFailsFastOnUnreachable(t *testing.T) {
	cfg := `{"outbounds":[{"protocol":"vless","settings":{"vnext":[{"address":"127.0.0.1","port":1,
	"users":[{"id":"b831381d-6324-4d53-ad4f-8cda48b30811","encryption":"none"}]}]}}]}`
	if d := MeasureDelay(cfg, "https://www.gstatic.com/generate_204", 2000); d != -1 {
		t.Fatalf("expected -1, got %d", d)
	}
}

// Loads the config generated by the Android app's ConfigBuilder
// (written by ConfigBuilderTest to app/build/generated-vpn-config.json).
func TestAndroidGeneratedConfigLoads(t *testing.T) {
	b, err := os.ReadFile("../app/build/generated-vpn-config.json")
	if err != nil {
		t.Skip("run `./gradlew :app:testDebugUnitTest` first")
	}
	inst, err := newInstance(string(b))
	if err != nil {
		t.Fatalf("app-generated config rejected by xray: %v", err)
	}
	inst.Close()
}
